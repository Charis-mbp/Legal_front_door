"""Build the importable n8n workflow from the playbook, the prompt and the JS sources.

The playbook (playbook.json) is the single source of truth for categories, owners,
deadlines, red-flag rules and approved answers. Edit it, then run:

    python3 scripts/build_workflow.py

and re-import n8n/legal-front-door.workflow.json into n8n.
"""
import json
import re
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "n8n" / "src"
OUT = ROOT / "n8n" / "legal-front-door.workflow.json"

TEAMS = ["Sales", "Care", "Product", "Marketing", "Partnerships", "People", "Operations", "Finance", "Other"]


def node_code(glue_file: str) -> str:
    playbook = json.loads((ROOT / "playbook.json").read_text(encoding="utf-8"))
    prompt = (ROOT / "prompts" / "classify_system.md").read_text(encoding="utf-8")
    core = (SRC / "core.js").read_text(encoding="utf-8")
    core = re.sub(r"\nif \(typeof module !== 'undefined'\) \{.*?\n\}\n", "\n", core, flags=re.S)
    glue = (SRC / glue_file).read_text(encoding="utf-8")
    return (
        "// GENERATED by scripts/build_workflow.py from playbook.json and n8n/src/.\n"
        "// Edit those files and rebuild rather than editing this node by hand.\n\n"
        f"const PLAYBOOK = {json.dumps(playbook, ensure_ascii=False, indent=2)};\n\n"
        f"const SYSTEM_PROMPT_TEMPLATE = {json.dumps(prompt, ensure_ascii=False)};\n\n"
        f"{core}\n{glue}"
    )


def nid() -> str:
    return str(uuid.uuid4())


def sticky(name, content, pos, width, height, color):
    return {
        "parameters": {"content": content, "width": width, "height": height, "color": color},
        "id": nid(), "name": name, "type": "n8n-nodes-base.stickyNote", "typeVersion": 1, "position": pos,
    }


